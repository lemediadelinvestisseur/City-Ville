const BY_ID = new Map(BUILDINGS.map((def) => [def.id, def]));

export function getBuildingDef(id: string): BuildingDef {
  const def = BY_ID.get(id);
  if (!def) throw new Error(`Construction inconnue : ${id}`);
  return def;
}

export function findBuildingDef(id: string): BuildingDef | undefined {
  return BY_ID.get(id);
}

